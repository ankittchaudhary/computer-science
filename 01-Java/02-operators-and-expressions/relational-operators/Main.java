public class Main {
    public static void main(String[] args) {
        //Relational Operators
        /*
        - Used for comparing the values

        <    less than
        <=   less than equal to
        >    greater than
        >=   greater than equal to
        ==   is equal to
        !=   not equal to

        */

        int a =5;
        int b =10;
        System.out.println(a<b); //true
        System.out.println(a<=b); //true 
        System.out.println(a>b); //false
        System.out.println(a>=b); //false
        System.out.println(a==b); //false
        System.out.println(a!=b); //true
    }
}
